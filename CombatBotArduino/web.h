/**
 * @file    web.h
 * @brief   声明设备网页服务的初始化与周期调度入口。
 *
 * ============================================================================
 * 模块职责：提供离线控制页面、配置 REST 接口与 WebSocket 控制和遥测通道。
 * 运行约定：网络初始化后调用 webBegin()，随后由主循环持续调用 webTick()。
 * 设计边界：网络层只受理请求；运动执行、控制权及失联保护由控制器管理。
 * ============================================================================
 */
#pragma once
namespace bot {

// ============================================================================
// 网页服务生命周期
// ============================================================================

/**
 * @brief   注册网页、REST 路由与 WebSocket 回调，并启动 HTTP 服务。
 * @details 启动阶段调用一次；网页资源已压缩并随固件内嵌，无需外网加载。
 */
void webBegin();

/**
 * @brief   周期推送遥测、清理连接，并检查延迟重启是否到期。
 * @details 由主循环持续调用；异步请求解析由服务器回调完成。
 */
void webTick();
}
