/**
 * @file    hardware.h
 * @brief   控制层使用的电机、舵机与传感器硬件接口。
 *
 * ============================================================================
 * 模块职责：向控制层提供初始化、驱动输出、四轮反馈和传感器快照入口。
 * 运行约定：先初始化，再由主控制循环调用；四轮数组固定按工程轮索引排列。
 * 设计边界：电机反馈方向来自 DIR 推断；撤驱动不等于主动制动。
 *           各传感器状态需分别检查，整体健康标志覆盖初始化、PWM 与 MPU 状态。
 * ============================================================================
 */
#pragma once
#include "types.h"
namespace bot {
// ============================================================================
// 启动与四轮驱动
// ============================================================================
/** @brief 建立电机、舵机、I2C 及传感器初始状态，电机从零占空比开始。 */
void hardwareBegin(const Config&);
/**
 * @brief   采样四轮累计脉冲、滤波线速度和轮转速。
 * @param dt 实际采样间隔，单位 s。
 * @param pulses 输出数组，至少 4 项；单位为带逻辑方向的 FG 上升沿数。
 * @param speed 输出数组，至少 4 项；单位 cm/s。
 * @param rpm 输出数组，至少 4 项；单位 rpm。
 * @note PCNT 展开要求相邻采样之间少于 30000 个边沿，目标周期为 10 ms。
 */
void motorSample(float dt, const Config&, int64_t pulses[4], float speed[4], float rpm[4]);
/**
 * @brief   对指定轮施加 PWM；换向前先撤驱动并等待反馈衰减。
 * @param index 轮索引 0~3。
 * @param signedPwm 符号为逻辑方向，绝对值为 0~1023 占空比计数。
 */
void motorWrite(int index, float signedPwm, const Config&);
/** @brief 将四轮 PWM 置零；不主动刹车，也不清空计数历史。 */
void motorStop();
/**
 * @brief   读取当前四轮已施加的占空比计数。
 * @param pwm 输出数组，至少 4 项，范围 0~1023。
 */
void motorOutputs(uint16_t pwm[4]);
// ============================================================================
// 辅助执行器与传感器快照
// ============================================================================
/**
 * @brief   按机构端点配置输出舵机位置。
 * @param pos 归一化位置，0 为下端、1 为上端，内部限幅至 0~1。
 */
void servoWrite(float pos, const Config&);
/** @brief 推进轮询并返回缓存快照；各类数值的可用性由对应有效标志表示。 */
Sensors sensorsRead(const Config&);
/** @brief 返回初始化、PWM 输出建立成功且 MPU 在线；不涵盖 IO、电池等传感器。 */
bool hardwareHealthy();
}
