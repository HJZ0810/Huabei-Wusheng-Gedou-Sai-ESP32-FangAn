/**
 * @file    wifi_mgr.h
 * @brief   控制热点、路由器连接及网络状态查询接口。
 *
 * ============================================================================
 * 模块职责：统一启动 AP + STA、处理 DNS，并报告客户端使用的网络地址。
 * 运行约定：网络参数在启动时复制，运行中的配置修改需重启后生效。
 * 设计边界：状态查询主要反映 STA 连接状态，不能代替实际连接或服务可达性检测。
 *           固定备用热点创建也可能失败，调用方应通过实际连接确认无线状态。
 * ============================================================================
 */
#pragma once
#include "types.h"
#include <Arduino.h>
namespace bot {
// ============================================================================
// 生命周期：启动一次，主循环持续推进
// ============================================================================
/** @brief 应用启动配置，尝试创建热点并启用 STA、DNS 与 mDNS。 */
void wifiBegin(const Config&);
/** @brief 处理 DNS 和 STA 定时重试；当前实现使用启动快照。 */
void wifiTick(const Config&);
// ============================================================================
// 查询接口：均不执行额外联网验证
// ============================================================================
/** @brief STA 已连接返回 AP_STA，否则返回 AP_ONLY；不保证 AP 创建成功。 */
String networkMode();
/** @brief 返回无线栈报告的 AP IP 地址。 */
String apIp();
/** @brief STA 已连接时返回 IP 地址，未连接时返回空字符串。 */
String staIp();
/** @brief STA 已连接时返回 RSSI（dBm），未连接时返回约定值 0。 */
int networkRssi();
}
